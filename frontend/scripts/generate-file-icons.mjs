function resolve(table, keys) {
  return Object.fromEntries(
    keys.map((key) => {
      const id = table[key];
      if (!id) throw new Error(`material-icon-theme ${version} has no icon for "${key}"`);
      return [key, id];
    }),
  );
}

const byName = resolve(manifest.fileNames, FILE_NAMES);
const byExtension = resolve(manifest.fileExtensions, EXTENSIONS);
const ids = [
  ...new Set([
    manifest.file,
    manifest.folder,
    manifest.folderExpanded,
    ...Object.values(byName),
    ...Object.values(byExtension),
  ]),
].sort();

// A `data:` URI keeps each SVG self-contained: no clashing `id`s or root
// attributes when two icons share a page, and no theme CSS leaking in.
function dataUri(id) {
  const svg = readFileSync(join(pack, "dist", manifest.iconDefinitions[id].iconPath), "utf8")
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim();
  if (svg.includes("'"))
    throw new Error(`${id}.svg holds a single quote; switch it to encodeURIComponent`);
  return (
    "data:image/svg+xml," + svg.replace(/"/g, "'").replace(/[%#<>{}|\\^`]/g, encodeURIComponent)
  );
}

const icons = Object.fromEntries(
  ids.map((id) => {
    // The pack's default icons are drawn for dark editors; a few ship a `_light` twin.
    const light = manifest.iconDefinitions[`${id}_light`] ? dataUri(`${id}_light`) : undefined;
    return [id, light ? { src: dataUri(id), lightSrc: light } : { src: dataUri(id) }];
  }),
);

